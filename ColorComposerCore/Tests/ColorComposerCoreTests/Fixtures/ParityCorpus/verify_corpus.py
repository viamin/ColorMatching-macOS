#!/usr/bin/env python3
"""Independent replay of the solver parity corpus (refresh-time sanity check).

The corpus at `v{N}/corpus.json` is mirrored verbatim from
viamin/color_matching `priv/parity/v{N}/corpus.json` (generated by
`ColorMatching.Parity.Corpus`, `mix parity.generate`). Every corpus file
records, per scenario, the scores/selection the *Elixir* solver produced.
This script re-derives those expectations from the scenario inputs using an
independent implementation of the documented policy:

  * score     = sum over light sources s with weight w > 0 of
                (candidate[s] - target[s])^2 * w
  * exclusion = candidate OR target is missing a measurement for any light
                source with weight > 0 ("missing" = key absent from
                `channels`; missing is NOT zero brightness)
  * selection = lowest score wins; exact ties break to the earliest index
  * weights   = unknown light-source keys are ignored; weight <= 0 channels
                neither exclude nor contribute

Run it after fetching a fresh corpus so a truncated or stale mirror fails
loudly before it is committed:

    python3 verify_corpus.py [path-to-corpus.json]

Exits 0 when every scenario's expected scores, selection, error, and tie
evidence match the independent replay exactly.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

LIGHT_SOURCES = ["white", "red", "green", "blue", "lps"]


def score(candidate: dict, target: dict, weights: dict):
    """Returns ('excluded' | float score) under the parity policy."""
    active = {s: w for s, w in weights.items() if s in LIGHT_SOURCES and w > 0}
    for vector in (candidate, target):
        for source in active:
            if source not in vector["channels"]:
                return "excluded"
    total = 0.0
    for source, weight in active.items():
        diff = vector_value(candidate, source) - vector_value(target, source)
        total += diff * diff * weight
    return total


def vector_value(vector: dict, source: str) -> float:
    value = vector["channels"].get(source, 0.0)
    return float(value)


def best_match(palette: list, target: dict, weights: dict):
    """Lowest score wins; earliest index wins exact ties. None when all excluded."""
    best = None
    for index, entry in enumerate(palette):
        result = score(entry, target, weights)
        if result == "excluded":
            continue
        if best is None or result < best[1]:
            best = (index, result)
    return best


def replay_scenario(scenario: dict) -> list[str]:
    problems: list[str] = []
    sid = scenario["id"]
    weights = scenario["weights"]
    palette = sorted(scenario["palette"], key=lambda e: e["index"])
    target = scenario["target"]
    expected = scenario["expected"]

    scored = [score(entry, target, weights) for entry in palette]
    best = best_match(palette, target, weights)

    for entry, computed in zip(sorted(expected["scores"], key=lambda s: s["index"]), scored):
        index, wanted = entry["index"], entry["score"]
        if wanted == "excluded":
            if computed != "excluded":
                problems.append(f"{sid}: index {index} expected excluded, computed {computed}")
        elif computed != wanted:
            problems.append(f"{sid}: index {index} expected {wanted}, computed {computed}")

    if expected["selected_index"] is None:
        if best is not None:
            problems.append(f"{sid}: expected no selection, computed {best}")
    else:
        if best is None:
            problems.append(f"{sid}: expected selection {expected['selected_index']}, computed none")
        else:
            index, error = best
            if index != expected["selected_index"]:
                problems.append(
                    f"{sid}: selected {index}, expected {expected['selected_index']}"
                )
            if error != expected["error"]:
                problems.append(f"{sid}: error {error}, expected {expected['error']}")
            if palette[index]["hex_color"] != expected["selected_hex_color"]:
                problems.append(f"{sid}: selected hex mismatch")

    if best is None:
        if expected["tied_indices"] != [] or expected["tie_broke"] is not None:
            problems.append(f"{sid}: expected empty tie evidence for null selection")
    else:
        error = best[1]
        tied = sorted(i for i, s in enumerate(scored) if s == error)
        if tied != expected["tied_indices"]:
            problems.append(f"{sid}: tied {tied}, expected {expected['tied_indices']}")
        if (len(tied) > 1) != expected["tie_broke"]:
            problems.append(f"{sid}: tie_broke {expected['tie_broke']}, tied {tied}")
        if tied[0] != expected["selected_index"]:
            problems.append(f"{sid}: earliest tied index {tied[0]} is not the selection")
    return problems


def default_corpus_path() -> Path:
    """Newest `v<N>/corpus.json` beside this script (v2 outranks v1)."""
    here = Path(__file__).resolve().parent
    versions = sorted(
        (p for p in here.glob("v*/corpus.json")),
        key=lambda p: int(p.parent.name.removeprefix("v")),
    )
    return versions[-1]


def main() -> int:
    path = Path(sys.argv[1]) if len(sys.argv) > 1 else default_corpus_path()
    corpus = json.loads(path.read_text(encoding="utf-8"))

    problems: list[str] = []
    if corpus.get("scorer") != "ColorMatching.WeightedSquaredError":
        problems.append(f"scorer stamp: {corpus.get('scorer')!r}")
    if corpus.get("selection") != "earliest-index-wins":
        problems.append(f"selection stamp: {corpus.get('selection')!r}")
    if corpus.get("missing_policy") != "excluded-when-any-positive-weight-channel-missing":
        problems.append(f"missing_policy stamp: {corpus.get('missing_policy')!r}")
    if corpus.get("light_sources") != LIGHT_SOURCES:
        problems.append(f"light_sources: {corpus.get('light_sources')!r}")

    scenarios = corpus.get("scenarios", [])
    ties = sum(1 for s in scenarios if s["expected"]["tie_broke"])
    nulls = sum(1 for s in scenarios if s["expected"]["selected_index"] is None)
    if ties < 1:
        problems.append("corpus contains no tie scenario")
    if nulls < 1:
        problems.append("corpus contains no null-selection scenario")

    for scenario in scenarios:
        problems.extend(replay_scenario(scenario))

    if problems:
        for problem in problems:
            print(f"MISMATCH {problem}", file=sys.stderr)
        print(f"FAIL {path}: {len(problems)} mismatch(es)", file=sys.stderr)
        return 1

    print(
        f"OK {path}: algorithm_version={corpus['algorithm_version']} "
        f"scenarios={len(scenarios)} ties={ties} null_selections={nulls}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
