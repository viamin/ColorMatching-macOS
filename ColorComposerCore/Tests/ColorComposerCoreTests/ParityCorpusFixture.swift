import Foundation
import ColorComposerCore

/// Errors thrown while loading or converting the parity corpus fixture.
enum ParityCorpusFixtureError: Error, LocalizedError {
    case fixtureMissing(String)
    case unparseableHex(String)
    case missingChannel(LightingCondition)

    var errorDescription: String? {
        switch self {
        case .fixtureMissing(let path):
            return "Parity corpus fixture is missing at \(path); see docs/solver-parity-corpus.md for how to refresh it."
        case .unparseableHex(let hex):
            return "Parity corpus contains an unparseable hex color: \(hex)"
        case .missingChannel(let condition):
            return "Parity corpus scenario is missing a channel required for a dense grid: \(condition.rawValue)"
        }
    }
}

/// Decoded shape of the solver parity corpus committed at
/// `Tests/ColorComposerCoreTests/Fixtures/Parity/v1/corpus.json`.
///
/// The fixture is a byte-identical copy of the corpus generated by the
/// `color_matching` server (`priv/parity/v1/corpus.json`, issue
/// viamin/color_matching#111) and is the shared source of truth that both
/// test suites replay: any divergence in missing-measurement exclusion,
/// earliest-index tie-breaking, or channel weighting between
/// `WeightedSquaredErrorScorer` and the Elixir `WeightedSquaredError` solver
/// shows up here as a mismatch.
struct ParityCorpus: Codable, Equatable {
    struct Vector: Codable, Equatable {
        /// Position in the scenario palette; `nil` for the target vector.
        let index: Int?
        let hexColor: String
        /// Brightness per light source; an absent key is an *unmeasured*
        /// channel (missing), never zero brightness.
        let channels: [String: Double]

        enum CodingKeys: String, CodingKey {
            case index
            case hexColor = "hex_color"
            case channels
        }
    }

    struct ExpectedScore: Codable, Equatable {
        let index: Int
        let score: CorpusScore
    }

    struct Expected: Codable, Equatable {
        let scores: [ExpectedScore]
        let selectedIndex: Int?
        let selectedHexColor: String?
        let error: Double?
        let tieBroke: Bool?
        let tiedIndices: [Int]

        enum CodingKeys: String, CodingKey {
            case scores
            case selectedIndex = "selected_index"
            case selectedHexColor = "selected_hex_color"
            case error
            case tieBroke = "tie_broke"
            case tiedIndices = "tied_indices"
        }
    }

    struct Scenario: Codable, Equatable {
        let id: String
        let description: String
        /// Weight per light source. Zero (or absent) means the channel is
        /// ignored; keys outside the canonical light sources (e.g.
        /// `ultraviolet` in `unknown-weight-ignored`) must be dropped when
        /// converting to `ChannelWeights`.
        let weights: [String: Double]
        let target: Vector
        let palette: [Vector]
        let expected: Expected
    }

    let algorithmVersion: Int
    let scorer: String
    let selection: String
    let missingPolicy: String
    let lightSources: [String]
    let scenarios: [Scenario]

    enum CodingKeys: String, CodingKey {
        case algorithmVersion = "algorithm_version"
        case scorer
        case selection
        case missingPolicy = "missing_policy"
        case lightSources = "light_sources"
        case scenarios
    }
}

/// One expected per-candidate outcome: either a finite score or `excluded`
/// under the corpus missing-measurement policy.
enum CorpusScore: Equatable, Decodable {
    case score(Double)
    case excluded

    init(from decoder: Decoder) throws {
        let container = try decoder.singleValueContainer()
        if let value = try? container.decode(Double.self) {
            self = .score(value)
            return
        }
        let raw = try container.decode(String.self)
        guard raw == "excluded" else {
            throw DecodingError.dataCorruptedError(
                in: container,
                debugDescription: "Unknown corpus score payload: \(raw)"
            )
        }
        self = .excluded
    }
}

/// Locates and decodes the committed corpus fixture.
///
/// The fixture resolves relative to this source file so the corpus loads
/// under `swift test` without a bundle-resource declaration in `Package.swift`.
enum ParityCorpusFixture {
    static let fixtureURL = URL(fileURLWithPath: #filePath)
        .deletingLastPathComponent()
        .appendingPathComponent("Fixtures/Parity/v1/corpus.json")

    static func load() throws -> ParityCorpus {
        guard let data = try? Data(contentsOf: fixtureURL) else {
            throw ParityCorpusFixtureError.fixtureMissing(fixtureURL.path)
        }
        return try JSONDecoder().decode(ParityCorpus.self, from: data)
    }
}

// MARK: - Domain conversion

extension ParityCorpus.Vector {
    /// Canonical (`LightingCondition`-backed) channels only — keys for light
    /// sources the app does not know are dropped, mirroring the server's
    /// handling of unknown sources.
    var canonicalChannels: [LightingCondition: Double] {
        var canonical: [LightingCondition: Double] = [:]
        for (key, value) in channels {
            if let condition = LightingCondition(rawValue: key) {
                canonical[condition] = value
            }
        }
        return canonical
    }

    /// The vector as a solver palette color. Unlisted channels stay
    /// unmeasured (absent from `responses`), matching the server's
    /// missing-vs-zero distinction.
    func toPaletteColor(id: Int) throws -> PaletteColor {
        guard let rgb = RGBColor(hex: hexColor) else {
            throw ParityCorpusFixtureError.unparseableHex(hexColor)
        }
        var responses: [LightingCondition: IlluminationResponse] = [:]
        for (condition, brightness) in canonicalChannels {
            responses[condition] = IlluminationResponse(brightness: brightness)
        }
        return PaletteColor(id: id, hex: hexColor, rgb: rgb, responses: responses)
    }

    /// The vector as a scorer target; absent channels stay absent.
    var toTarget: TargetResponseVector {
        TargetResponseVector(canonicalChannels)
    }
}

extension ParityCorpus.Scenario {
    /// Weights restricted to canonical light sources; unknown keys are
    /// ignored, matching `ColorMatching.WeightedSquaredError`'s
    /// `filter_weights/1` (exercised by `unknown-weight-ignored`).
    var channelWeights: ChannelWeights {
        var canonical: [LightingCondition: Double] = [:]
        for (key, value) in weights {
            if let condition = LightingCondition(rawValue: key) {
                canonical[condition] = value
            }
        }
        return ChannelWeights(
            white: canonical[.white] ?? 0,
            red: canonical[.red] ?? 0,
            green: canonical[.green] ?? 0,
            blue: canonical[.blue] ?? 0,
            lps: canonical[.lps] ?? 0
        )
    }

    /// The scenario palette in corpus index order, ready for the solver.
    func paletteColors() throws -> [PaletteColor] {
        var colors: [PaletteColor] = []
        for (offset, vector) in palette.enumerated() {
            colors.append(try vector.toPaletteColor(id: offset))
        }
        return colors
    }

    /// Conditions with positive weight — the channels the scorer requires.
    var activeConditions: Set<LightingCondition> {
        Set(channelWeights.activeConditions)
    }

    /// `true` when the target measures every active channel, i.e. the
    /// scenario is expressible as dense solver source grids. The
    /// `missing-target-excluded` scenario deliberately fails this: a
    /// `BrightnessGrid` target always exists, so its every-candidate-excluded
    /// outcome is only observable at the scorer level.
    var isExpressibleAsSourceGrids: Bool {
        let targetChannels = target.canonicalChannels
        return activeConditions.allSatisfy { targetChannels[$0] != nil }
    }

    /// 1×1 source grids per active condition, filled from the target vector —
    /// feeds the scenario through the solver's production fast path.
    func sourceGrids() throws -> [LightingCondition: BrightnessGrid] {
        let targetChannels = target.canonicalChannels
        var grids: [LightingCondition: BrightnessGrid] = [:]
        for condition in channelWeights.activeConditions {
            guard let value = targetChannels[condition] else {
                throw ParityCorpusFixtureError.missingChannel(condition)
            }
            grids[condition] = BrightnessGrid(width: 1, height: 1, values: [value])
        }
        return grids
    }
}
