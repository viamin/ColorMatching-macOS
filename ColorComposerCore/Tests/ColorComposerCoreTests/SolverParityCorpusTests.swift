import Foundation
import XCTest
@testable import ColorComposerCore

/// Solver parity harness for the `color_matching` corpus (viamin/color_matching#111).
///
/// The corpus pins `WeightedSquaredErrorScorer` — and the solver's selection
/// policy around it — to the Elixir `ColorMatching.WeightedSquaredError` /
/// `IlluminantMatching.best_match/4` behavior. Every JSON corpus committed
/// under `Fixtures/Parity/` is executed against the real `CompositionSolver`
/// through a 1×1 brightness grid per active channel, so each corpus case is a
/// true end-to-end selection: scoring, required-channel exclusion, and
/// earliest-index tie-breaking all run through production code paths.
///
/// Two corpora live there:
///
/// - `weighted_squared_error_corpus.seed.json` — a hand-computed seed that
///   documents the format and pins the parity rules the harness itself relies
///   on (ties, exclusions, weight handling, absence-vs-zero).
/// - `weighted_squared_error_corpus.json` — the committed upstream corpus
///   generated by the Elixir service. `testUpstreamParityCorpusIsCommitted`
///   fails until it is committed; see `docs/solver-parity-corpus.md` for the
///   refresh procedure.
final class SolverParityCorpusTests: XCTestCase {
    private static let fixturesDirectory = URL(fileURLWithPath: #filePath)
        .deletingLastPathComponent()
        .appendingPathComponent("Fixtures/Parity", isDirectory: true)

    private static let upstreamCorpusFilename = "weighted_squared_error_corpus.json"

    // MARK: - Corpus presence

    /// The upstream parity corpus from viamin/color_matching#111 must be
    /// committed for this harness to assert real cross-implementation parity.
    /// The seed corpus alone only exercises cases written from the Swift side.
    func testUpstreamParityCorpusIsCommitted() throws {
        let url = Self.fixturesDirectory.appendingPathComponent(Self.upstreamCorpusFilename)
        guard FileManager.default.fileExists(atPath: url.path) else {
            XCTFail(
                "Upstream parity corpus is missing at \(url.path). Commit the corpus generated by "
                    + "viamin/color_matching#111 there — see docs/solver-parity-corpus.md."
            )
            return
        }
        _ = try Self.loadCorpus(at: url)
    }

    // MARK: - Corpus integrity

    /// Every corpus — seed and upstream — must declare the generator module it
    /// pins, so a corpus produced by any other solver can never be consumed
    /// here by accident.
    func testEveryCorpusDeclaresWeightedSquaredErrorGenerator() throws {
        for (url, corpus) in try Self.loadAllCorpora() {
            XCTAssertEqual(
                corpus.generator.module,
                "ColorMatching.WeightedSquaredError",
                "\(url.lastPathComponent): generator.module must name the Elixir scorer the corpus pins"
            )
            XCTAssertEqual(corpus.version, 1, "\(url.lastPathComponent): unsupported corpus version")
            XCTAssertFalse(corpus.cases.isEmpty, "\(url.lastPathComponent): corpus carries no cases")
        }
    }

    /// Tie cases and exclusion cases are required content, not optional: a
    /// corpus refresh that silently drops either would quietly narrow what
    /// "parity" means. The issue explicitly demands tie coverage.
    func testEveryCorpusCoversTiesAndExclusions() throws {
        for (url, corpus) in try Self.loadAllCorpora() {
            let hasTie = corpus.cases.contains { $0.expected.tie == true }
            let hasExclusion = corpus.cases.contains { !($0.expected.excludedIds ?? []).isEmpty }
            XCTAssertTrue(hasTie, "\(url.lastPathComponent): no tie case found — corpus must cover earliest-index tie-breaking")
            XCTAssertTrue(hasExclusion, "\(url.lastPathComponent): no exclusion case found — corpus must cover missing-required-channel exclusion")
        }
    }

    // MARK: - Parity

    func testSolverSelectionsMatchCorpusExpectations() throws {
        var failures: [String] = []
        var executedCases = 0

        for (url, corpus) in try Self.loadAllCorpora() {
            for testCase in corpus.cases {
                executedCases += 1
                Self.run(testCase, corpus: url.lastPathComponent, into: &failures)
            }
        }

        XCTAssertGreaterThan(executedCases, 0, "no corpus cases were executed")
        if !failures.isEmpty {
            XCTFail("Parity failures (\(failures.count)):\n" + failures.joined(separator: "\n"))
        }
    }

    /// The seed corpus is the in-repo format reference and must always stay
    /// present and decodable; its cases run in the parity test above.
    func testSeedCorpusStaysIntact() throws {
        let url = Self.fixturesDirectory.appendingPathComponent("weighted_squared_error_corpus.seed.json")
        let corpus = try Self.loadCorpus(at: url)
        XCTAssertGreaterThanOrEqual(corpus.cases.count, 8, "seed corpus lost cases — do not shrink it")
    }

    // MARK: - Case execution

    private static func run(_ testCase: ParityCorpus.Case, corpus: String, into failures: inout [String]) {
        func fail(_ message: String) {
            failures.append("\(corpus) · case \(testCase.id): \(message)")
        }

        guard let weights = ChannelWeights(responses: testCase.weights) else {
            return fail("weights name an unknown light source or carry no positive weight: \(testCase.weights)")
        }

        var palette: [PaletteColor] = []
        for candidate in testCase.palette {
            guard let color = Self.makeColor(candidate) else {
                return fail("candidate \(candidate.id) names an unknown light source: \(candidate.responses)")
            }
            palette.append(color)
        }

        let activeConditions = weights.activeConditions
        var grids: [LightingCondition: BrightnessGrid] = [:]
        for condition in activeConditions {
            guard let brightness = testCase.target[condition.rawValue] else {
                return fail("target lacks the active condition \(condition.rawValue)")
            }
            grids[condition] = BrightnessGrid(width: 1, height: 1, fill: brightness)
        }

        let result: CompositionResult
        do {
            result = try CompositionSolver().solve(palette: palette, sourceGrids: grids, weights: weights)
        } catch {
            return fail("solver threw \(error)")
        }

        let expected = testCase.expected
        // `colorIndices` is [Int?]; `first` is Int?? — coalesce the outer level
        // so "no cell match" (a nil element) is distinguishable from "no cell".
        let selectedCell = result.colorIndices.first ?? nil
        let selectedID = selectedCell.map { palette[$0].id }

        if let expectedID = expected.selectedId {
            guard selectedID == expectedID else {
                return fail("selected color \(String(describing: selectedID)), expected \(expectedID)")
            }
        } else {
            guard selectedCell == nil else {
                return fail("selected color \(String(describing: selectedID)), expected no selection")
            }
            XCTAssertEqual(result.unmatchedCellCount, 1, corpus + " · case " + testCase.id)
        }

        if let expectedScore = expected.score, selectedID != nil {
            XCTAssertEqual(
                result.errors.first ?? .infinity,
                expectedScore,
                accuracy: 1e-9,
                "\(corpus) · case \(testCase.id): selected-color score"
            )
        }

        let excludedIDs = Set(palette.filter { color in
            !activeConditions.allSatisfy { color.brightness(for: $0) != nil }
        }.map(\.id))
        XCTAssertEqual(
            excludedIDs,
            Set(expected.excludedIds ?? []),
            "\(corpus) · case \(testCase.id): excluded candidates"
        )
        XCTAssertEqual(
            result.excludedCandidateCount,
            excludedIDs.count,
            "\(corpus) · case \(testCase.id): solver excluded-candidate count"
        )

        if let tie = expected.tie {
            let winners = Self.bestScoreWinnerCount(palette: palette, testCase: testCase, weights: weights)
            if tie {
                XCTAssertGreaterThanOrEqual(
                    winners,
                    2,
                    "\(corpus) · case \(testCase.id): flagged as a tie but only \(winners) candidate(s) attain the best score"
                )
            } else {
                XCTAssertEqual(
                    winners,
                    1,
                    "\(corpus) · case \(testCase.id): flagged as a unique winner but \(winners) candidates tie on the best score"
                )
            }
        }
    }

    /// A corpus candidate becomes a domain color. Unlike API payloads, corpus
    /// keys are a controlled vocabulary: any unknown light-source name is a
    /// generator bug and fails the case instead of being dropped.
    private static func makeColor(_ candidate: ParityCorpus.Case.Candidate) -> PaletteColor? {
        var responses: [LightingCondition: IlluminationResponse] = [:]
        for (key, brightness) in candidate.responses {
            guard let condition = LightingCondition(rawValue: key) else { return nil }
            responses[condition] = IlluminationResponse(brightness: brightness)
        }
        return PaletteColor(
            id: candidate.id,
            hex: candidate.hexLabel,
            rgb: RGBColor(hex: candidate.hexLabel)!,
            responses: responses
        )
    }

    /// How many candidates attain the minimal score — 1 means a unique winner,
    /// 2 or more means a tie the selection policy must break by earliest index.
    private static func bestScoreWinnerCount(
        palette: [PaletteColor],
        testCase: ParityCorpus.Case,
        weights: ChannelWeights
    ) -> Int {
        let scorer = WeightedSquaredErrorScorer()
        var targetBrightness: [LightingCondition: Double] = [:]
        for condition in weights.activeConditions {
            targetBrightness[condition] = testCase.target[condition.rawValue] ?? 0
        }
        let target = TargetResponseVector(targetBrightness)

        var best = Double.infinity
        var scores: [Double] = []
        for color in palette {
            guard case .score(let value) = scorer.score(candidate: color, target: target, weights: weights) else {
                continue
            }
            scores.append(value)
            best = Swift.min(best, value)
        }
        return scores.filter { abs($0 - best) <= 1e-12 }.count
    }

    // MARK: - Loading

    private static func loadAllCorpora() throws -> [(URL, ParityCorpus)] {
        let files = (try? FileManager.default.contentsOfDirectory(
            at: fixturesDirectory,
            includingPropertiesForKeys: nil
        )) ?? []
        return try files
            .filter { $0.pathExtension == "json" }
            .sorted { $0.lastPathComponent < $1.lastPathComponent }
            .map { ($0, try loadCorpus(at: $0)) }
    }

    private static func loadCorpus(at url: URL) throws -> ParityCorpus {
        let decoder = JSONDecoder()
        decoder.keyDecodingStrategy = .convertFromSnakeCase
        do {
            return try decoder.decode(ParityCorpus.self, from: try Data(contentsOf: url))
        } catch {
            XCTFail("Corpus \(url.lastPathComponent) is not decodable: \(error)")
            throw error
        }
    }
}

// MARK: - Corpus wire format

/// The JSON contract this harness consumes. The seed fixture under
/// `Fixtures/Parity/` is the executable format reference.
private struct ParityCorpus: Codable {
    struct Generator: Codable {
        let module: String
        let source: String?
        let commit: String?
    }

    struct Case: Codable {
        struct Candidate: Codable {
            let id: Int
            let responses: [String: Double]

            /// Selection depends only on the response vector; the visual color
            /// is synthesized deterministically from the candidate id.
            var hexLabel: String { String(format: "#%06x", UInt32(bitPattern: Int32(clamping: id))) }
        }

        struct Expected: Codable {
            let selectedId: Int?
            let score: Double?
            let tie: Bool?
            let excludedIds: [Int]?
        }

        let id: String
        let description: String?
        let weights: [String: Double]
        let target: [String: Double]
        let palette: [Candidate]
        let expected: Expected
    }

    let version: Int
    let generator: Generator
    let cases: [Case]
}

private extension ChannelWeights {
    /// Builds weights from corpus light-source names, failing on unknown keys
    /// or an all-zero vector (the solver requires at least one active channel).
    init?(responses: [String: Double]) {
        var weights = ChannelWeights()
        for (key, value) in responses {
            switch key {
            case "white": weights.white = value
            case "red": weights.red = value
            case "green": weights.green = value
            case "blue": weights.blue = value
            case "lps": weights.lps = value
            else: return nil
            }
        }
        guard !weights.activeConditions.isEmpty else { return nil }
        self = weights
    }
}
