import Foundation
import XCTest
@testable import ColorComposerCore

/// Solver-parity corpus consumption (issue #39; depends on the corpus
/// published by viamin/color_matching#111).
///
/// Every `*.json` file in `Fixtures/ParityCorpus` is a corpus of selection
/// cases produced against the Elixir `WeightedSquaredError` solver. Each case
/// is replayed against `WeightedSquaredErrorScorer` and must agree *exactly*:
///
/// - the selected candidate id (including ties, which must resolve to the
///   earliest candidate in array order — mirroring `CompositionSolver` and the
///   Elixir `IlluminantMatching.best_match/4` earliest-wins policy),
/// - the winning score (within `1e-9`),
/// - which candidates are excluded (missing measurement for any required
///   condition on the candidate **or** the target),
/// - that zero-weight channels neither participate nor exclude.
///
/// Files:
/// - `seed-corpus.json` — hand-computed seed pinning the consumption format.
/// - `weighted-squared-error-corpus.json` — the canonical corpus generated by
///   the Elixir service; `testCanonicalUpstreamCorpusIsCommitted` fails until
///   it is committed (refresh instructions: `docs/solver-parity-corpus.md`).
final class SolverParityCorpusTests: XCTestCase {
    private static let tieEpsilon = 1e-12
    private static let scoreAccuracy = 1e-9
    private static let canonicalCorpusFileName = "weighted-squared-error-corpus.json"

    private static let corpusDirectory = URL(fileURLWithPath: #filePath)
        .deletingLastPathComponent()
        .appendingPathComponent("Fixtures/ParityCorpus", isDirectory: true)

    // MARK: - Corpus presence

    /// The canonical corpus from viamin/color_matching#111 must be committed.
    /// This is the red-phase guard for the parity-corpus deliverable: it fails
    /// until the generated corpus lands at the canonical path.
    func testCanonicalUpstreamCorpusIsCommitted() {
        let url = Self.corpusDirectory.appendingPathComponent(Self.canonicalCorpusFileName)

        XCTAssertTrue(
            FileManager.default.fileExists(atPath: url.path),
            "Missing \(url.path): commit the solver parity corpus generated by color_matching "
                + "(viamin/color_matching#111). See docs/solver-parity-corpus.md for the format "
                + "and refresh procedure."
        )
    }

    // MARK: - Replay

    /// Replays every committed corpus file against the Swift scorer. The seed
    /// corpus validates the harness today; the canonical corpus joins once
    /// committed and any divergence from the Elixir solver fails here.
    func testCommittedCorpusFilesReplayWithExactParity() throws {
        let files = try FileManager.default.contentsOfDirectory(atPath: Self.corpusDirectory.path)
            .filter { $0.hasSuffix(".json") }
            .sorted()

        XCTAssertFalse(files.isEmpty, "No corpus files found in \(Self.corpusDirectory.path)")
        for file in files {
            try replayCorpus(named: file)
        }
    }

    private func replayCorpus(named fileName: String) throws {
        let url = Self.corpusDirectory.appendingPathComponent(fileName)
        let decoder = JSONDecoder()
        decoder.keyDecodingStrategy = .convertFromSnakeCase
        let corpus = try decoder.decode(
            ParityCorpus.self,
            from: try Data(contentsOf: url)
        )

        XCTAssertEqual(corpus.version, 1, "\(fileName): unsupported corpus format version")
        XCTAssertEqual(corpus.scorer, "WeightedSquaredError", "\(fileName): unexpected scorer \(corpus.scorer ?? "nil")")

        for testCase in corpus.cases {
            try replay(testCase, corpusFile: fileName)
        }
    }

    // MARK: - Per-case replay

    private func replay(_ testCase: ParityCase, corpusFile: String) throws {
        let weights = try makeWeights(testCase.weights, caseID: testCase.id, corpusFile: corpusFile)
        let target = try makeTarget(testCase.target, caseID: testCase.id, corpusFile: corpusFile)
        var scored: [ScoredCandidate] = []
        var excludedIDs: [Int] = []
        var selection: ScoredCandidate?

        for (index, candidate) in testCase.candidates.enumerated() {
            let color = try makeColor(candidate, caseID: testCase.id, corpusFile: corpusFile)
            switch WeightedSquaredErrorScorer().score(candidate: color, target: target, weights: weights) {
            case .excluded:
                excludedIDs.append(candidate.id)
            case .score(let value):
                let entry = ScoredCandidate(id: candidate.id, index: index, score: value)
                scored.append(entry)
                if value < (selection?.score ?? .infinity) {
                    selection = entry
                }
            }
        }

        assertSelection(testCase.expected, selection: selection, scored: scored,
                        caseID: testCase.id, corpusFile: corpusFile)
        assertExclusions(testCase.expected, excludedIDs: excludedIDs,
                         caseID: testCase.id, corpusFile: corpusFile)
    }

    private func assertSelection(
        _ expected: ParityExpectation,
        selection: ScoredCandidate?,
        scored: [ScoredCandidate],
        caseID: String,
        corpusFile: String,
        file: StaticString = #filePath,
        line: UInt = #line
    ) {
        let label = "\(corpusFile)/\(caseID)"
        let summary = "scores: \(scored.map { "\($0.id)=\($0.score)" }.joined(separator: ", "))"

        switch expected.selectedID {
        case .some(let id):
            guard let winner = selection else {
                return XCTFail("\(label): expected selection \(id) but every candidate was excluded",
                               file: file, line: line)
            }
            XCTAssertEqual(winner.id, id, "\(label): selection mismatch (\(summary))", file: file, line: line)
            assertTie(expected, winner: winner, scored: scored, label: label, file: file, line: line)
            if let expectedScore = expected.score {
                XCTAssertEqual(winner.score, expectedScore, accuracy: Self.scoreAccuracy,
                               "\(label): winning score mismatch", file: file, line: line)
            }
        case .none:
            var winnerID: Int?
            if let selection { winnerID = selection.id }
            XCTAssertNil(selection, "\(label): expected no selection but candidate \(winnerID.map(String.init) ?? "?") won (\(summary))", file: file, line: line)
        }
    }

    /// A case marked `tie: true` must have the winner tie at least one other
    /// candidate and be the earliest of the tied group; a case not marked tie
    /// must have a strictly better winner, so tie markers stay trustworthy.
    private func assertTie(
        _ expected: ParityExpectation,
        winner: ScoredCandidate,
        scored: [ScoredCandidate],
        label: String,
        file: StaticString = #filePath,
        line: UInt = #line
    ) {
        let tied = scored.filter { abs($0.score - winner.score) <= Self.tieEpsilon }
        let others = tied.filter { $0.index != winner.index }

        if expected.tie == true {
            XCTAssertFalse(others.isEmpty,
                           "\(label): marked as a tie but no other candidate ties the winner (tied: \(tied.map(\.id)))",
                           file: file, line: line)
            XCTAssertEqual(tied.map(\.index).min(), winner.index,
                           "\(label): tie must resolve to the earliest tied candidate",
                           file: file, line: line)
        } else {
            for other in others {
                XCTAssertGreaterThan(other.score, winner.score,
                                     "\(label): not marked as a tie but candidate \(other.id) ties the winner — corpus tie marker is wrong or the Swift scorer diverges",
                                     file: file, line: line)
            }
        }
    }

    private func assertExclusions(
        _ expected: ParityExpectation,
        excludedIDs: [Int],
        caseID: String,
        corpusFile: String,
        file: StaticString = #filePath,
        line: UInt = #line
    ) {
        guard let expectedExcluded = expected.excludedIDs else { return }
        XCTAssertEqual(excludedIDs.sorted(), expectedExcluded.sorted(),
                       "\(corpusFile)/\(caseID): excluded candidate mismatch",
                       file: file, line: line)
    }

    // MARK: - Corpus → domain conversion

    private func makeWeights(
        _ map: [String: Double],
        caseID: String,
        corpusFile: String
    ) throws -> ChannelWeights {
        var weights = ChannelWeights()
        for (key, value) in map {
            let condition = try canonicalCondition(key, caseID: caseID, corpusFile: corpusFile)
            switch condition {
            case .white: weights.white = value
            case .red: weights.red = value
            case .green: weights.green = value
            case .blue: weights.blue = value
            case .lps: weights.lps = value
            }
        }
        return weights
    }

    private func makeTarget(
        _ map: [String: Double],
        caseID: String,
        corpusFile: String
    ) throws -> TargetResponseVector {
        var brightness: [LightingCondition: Double] = [:]
        for (key, value) in map {
            brightness[try canonicalCondition(key, caseID: caseID, corpusFile: corpusFile)] = value
        }
        return TargetResponseVector(brightness)
    }

    private func makeColor(
        _ candidate: ParityCandidate,
        caseID: String,
        corpusFile: String
    ) throws -> PaletteColor {
        var responses: [LightingCondition: IlluminationResponse] = [:]
        for (key, brightness) in candidate.responses {
            let condition = try canonicalCondition(key, caseID: caseID, corpusFile: corpusFile)
            responses[condition] = IlluminationResponse(brightness: brightness)
        }
        return PaletteColor(
            id: candidate.id,
            name: "Candidate \(candidate.id)",
            hex: "#000000",
            rgb: RGBColor(red: 0, green: 0, blue: 0),
            responses: responses
        )
    }

    private func canonicalCondition(
        _ key: String,
        caseID: String,
        corpusFile: String
    ) throws -> LightingCondition {
        guard let condition = LightingCondition(rawValue: key) else {
            XCTFail("\(corpusFile)/\(caseID): unknown light source '\(key)' — corpus and LightingCondition disagree")
            throw CocoaError(.fileReadCorruptFile)
        }
        return condition
    }
}

// MARK: - Corpus wire format

private struct ScoredCandidate {
    let id: Int
    let index: Int
    let score: Double
}

private struct ParityCorpus: Codable {
    let version: Int
    let scorer: String?
    let cases: [ParityCase]
}

private struct ParityCandidate: Codable {
    let id: Int
    let responses: [String: Double]
}

private struct ParityCase: Codable {
    let id: String
    let description: String?
    let weights: [String: Double]
    let target: [String: Double]
    let candidates: [ParityCandidate]
    let expected: ParityExpectation
}

private struct ParityExpectation: Codable {
    let selectedID: Int?
    let score: Double?
    let tie: Bool?
    let excludedIDs: [Int]?
}
